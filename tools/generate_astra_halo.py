"""Generate Astra's fixed RGB565 halo; standard library only, no runtime blur."""
import math
from pathlib import Path

SIZE = 176
COLORS = (0x57E5FF, 0x56AFFF, 0x655BFF, 0xA279FF, 0xDB9AFF, 0x478BFF)


def pixels():
    result = bytearray()
    for y in range(SIZE):
        for x in range(SIZE):
            dx, dy = x - (SIZE - 1) / 2, y - (SIZE - 1) / 2
            distance = math.hypot(dx, dy) - 56.5
            angle = (math.atan2(dy, dx) % math.tau) / math.tau * len(COLORS)
            index, blend = int(angle), angle % 1
            # Broader outside glow, smoothly extinguished before the canvas
            # edge. Keep the interior dim and the bright face outline unchanged.
            fade = max(0, min(1, (31 - distance) / 12))
            fade = fade * fade * (3 - 2 * fade)
            glow = (0.13 * math.exp(-0.5 * (distance / 16.0) ** 2) * fade
                    if distance > 0 else 0.045 * math.exp(-0.5 * (distance / 8.0) ** 2))
            strength = min(1, 0.88 * math.exp(-0.5 * (distance / 1.6) ** 2)
                           + 0.19 * math.exp(-0.5 * (distance / 4.0) ** 2)
                           + glow)
            a, b = COLORS[index], COLORS[(index + 1) % len(COLORS)]
            rgb = [round((((a >> shift) & 255) * (1 - blend)
                          + ((b >> shift) & 255) * blend) * strength)
                   for shift in (16, 8, 0)]
            value = (rgb[0] >> 3) << 11 | (rgb[1] >> 2) << 5 | rgb[2] >> 3
            result.extend(value.to_bytes(2, "little"))
    return result


if __name__ == "__main__":
    data = pixels()
    output = Path(__file__).resolve().parents[1] / "components/watch-ui/astra_halo.h"
    lines = ["#pragma once", "#include <stdint.h>",
             "// Generated by tools/generate_astra_halo.py. RGB565, little endian.",
             f"// Fixed {SIZE} x {SIZE} image on black; no runtime blur or animation.",
             f"static constexpr unsigned astra_halo_size = {SIZE};",
             "alignas(4) static const uint8_t astra_halo_pixels[] = {"]
    lines += ["    " + ",".join(f"0x{v:02x}" for v in data[i:i+24]) + ","
              for i in range(0, len(data), 24)]
    lines += ["};", ""]
    output.write_text("\n".join(lines), encoding="utf-8")
